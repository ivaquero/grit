//go:embed defaults/*.toml defaults/plugins/*.toml defaults/files/*
var defaultsFS embed.FS

// version 由构建时注入：-ldflags "-X main.version=0.1.0"。
var version = "0.1.0-dev"

func main() {
	if len(os.Args) < 2 {
		usage()
		os.Exit(2)
	}

	var err error
	switch os.Args[1] {
	case "init":
		err = cmdInit(os.Args[2:])
	case "state":
		err = cmdState(os.Args[2:])
	case "shell":
		err = cmdShell(os.Args[2:])
	case "list":
		err = cmdList(os.Args[2:])
	case "file":
		err = cmdFile(os.Args[2:])
	case "migrate":
		err = cmdMigrate(os.Args[2:])
	case "self-update":
		err = cmdSelfUpdate(os.Args[2:])
	case "conv":
		err = cmdConv(os.Args[2:])
	case "complete":
		err = cmdComplete(os.Args[2:])
	case "completion":
		err = cmdCompletion(os.Args[2:])
	case "version", "--version", "-v":
		fmt.Println("grit " + version)
	default:
		usage()
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "grit: %v\n", err)
		os.Exit(1)
	}
}

func usage() {
	fmt.Fprint(os.Stderr, `grit — declarative shell and dotfile assembler

  grit init --shell <bash|zsh|pwsh> [--only-installed]
                                    generate shell integration
  grit state <plugin> <action> [args] print shell code to eval (state channel)
  grit shell export <key> <value>     print one export in the target shell syntax
  grit file <backup|restore|catalyze|propagate> [-n] <key>...
  grit migrate [--from <json>] [--to <toml>] [-n] [-f]
  grit self-update [-f] [--no-plugins]
  grit conv <name> <file>             convert a file in place
  grit completion --shell <sh>        print a shell completion script
  grit complete <context>             print candidates (used by the script)
  grit list <aliases|plugins|elements|conv>
`)
}

func loadConfig() (*config.Config, error) {
	return config.Load(defaultsFS, "defaults")
}

// targetShell 解析目标 shell：--shell 优先，其次 GRIT_SHELL，最后 bash。
func targetShell(explicit string, args []string) (shell.Shell, error) {
	name := explicit
	for i := 0; i < len(args); i++ {
		if (args[i] == "--shell" || args[i] == "-s") && i+1 < len(args) {
			name = args[i+1]
			i++
		}
	}
	if name == "" {
		name = os.Getenv("GRIT_SHELL")
	}
	if name == "" {
		name = "bash"
	}
	return shell.Get(name)
}

func cmdInit(args []string) error {
	sh, err := targetShell("", args)
	if err != nil {
		return err
	}
	cfg, err := loadConfig()
	if err != nil {
		return err
	}

	// 默认全量生成：命令暂时不在 PATH 不等于用户不需要那个别名。
	onlyInstalled := false
	for _, a := range args {
		if a == "--only-installed" {
			onlyInstalled = true
		}
	}
	// 每个插件只判定一次，避免 actions 与 state 各打印一遍跳过原因。
	isEnabled := make(map[string]bool, len(cfg.Order))
	for _, pname := range cfg.Order {
		p := cfg.Plugins[pname]
		ok := matchesOS(p.OS)
		if ok && onlyInstalled && p.Requires != "" {
			if _, err := exec.LookPath(p.Requires); err != nil {
				fmt.Fprintf(os.Stderr, "skip %s: %s not found in PATH\n", p.Name, p.Requires)
				ok = false
			}
		}
		isEnabled[pname] = ok
	}

	isWin := sh.Name() == "pwsh"

	root := gritRoot(isWin)

	var b strings.Builder
	fmt.Fprintf(&b, "# Grit — generated by `grit init --shell %s`. Do not edit.\n", sh.Name())
	b.WriteString("# Source of truth: defaults/*.toml. Regenerate after any change.\n\n")

	b.WriteString(sh.Export("GRIT", root) + "\n")
	b.WriteString(sh.Export("GRIT_SHELL", sh.Name()) + "\n\n")

	var pairs [][2]string
	for _, e := range cfg.Elements {
		// 平台分支看目标 shell，不看宿主 OS：
		// Windows 上跑 Git Bash 需要 POSIX 风格的路径。
		p := e.Unix
		if isWin {
			p = e.Win
		}
		if p == "" {
			continue
		}
		pairs = append(pairs, [2]string{e.Key, ospath.Expand(p, isWin)})
	}
	b.WriteString(sh.Assoc("GRIT_ELEMENT", pairs) + "\n\n")

	b.WriteString("# --- aliases ---\n")
	for _, a := range cfg.Aliases {
		if !matchesOS(a.OS) {
			continue
		}
		b.WriteString(sh.Alias(a.Name, a.Cmd) + "\n")
	}

	b.WriteString("\n# --- package managers ---\n")
	for _, pname := range cfg.Order {
		p := cfg.Plugins[pname]
		if !isEnabled[pname] {
			continue
		}
		for _, k := range sortedKeys(p.Actions) {
			b.WriteString(sh.Alias(p.Abbr+k, p.Actions[k]) + "\n")
		}
	}

	b.WriteString("\n# --- conversions ---\n")
	seenConv := make(map[string]bool, len(cfg.Converts))
	for _, cv := range cfg.Converts {
		if !matchesOS(cv.OS) || seenConv[cv.Name] {
			continue
		}
		seenConv[cv.Name] = true
		b.WriteString(sh.Alias(cv.Name, "grit conv "+cv.Name) + "\n")
	}

	b.WriteString("\n# --- state channel: these must mutate the current shell ---\n")
	for _, pname := range cfg.Order {
		p := cfg.Plugins[pname]
		if !isEnabled[pname] {
			continue
		}
		keys := make([]string, 0, len(p.State))
		for k := range p.State {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			b.WriteString(sh.State(k, p.Name, k) + "\n")
		}
	}

	_, err = os.Stdout.WriteString(b.String())
	return err
}

func cmdState(args []string) error {
	if len(args) < 2 {
		return fmt.Errorf("usage: grit state <plugin> <action> [args...]")
	}
	pluginName, action, rest := args[0], args[1], args[2:]

	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	p, ok := cfg.Plugin(pluginName)
	if !ok {
		return fmt.Errorf("unknown plugin %q", pluginName)
	}
	tmpl, ok := p.State[action]
	if !ok {
		return fmt.Errorf("plugin %q has no state action %q", pluginName, action)
	}

	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}

	cmdline := strings.ReplaceAll(tmpl, "{shell}", sh.Interpreter())
	if self, e := os.Executable(); e == nil {
		cmdline = strings.ReplaceAll(cmdline, "{self}", sh.Quote(self))
	}
	if len(rest) > 0 {
		quoted := make([]string, len(rest))
		for i, a := range rest {
			quoted[i] = sh.Quote(a)
		}
		cmdline = strings.ReplaceAll(cmdline, "{0}", strings.Join(quoted, " "))
	} else {
		// 无参数时把占位符连同前导空格一起去掉，让模板退化成无参调用。
		cmdline = strings.ReplaceAll(cmdline, " {0}", "")
	}

	return runShell(sh, cmdline)
}

// runShell 执行一条命令并把它的输出原样交给调用方 shell 去 eval。
// grit 不计算环境，只做路由：真正懂「怎么改环境」的是被调用的工具。
func runShell(sh shell.Shell, cmdline string) error {
	var c *exec.Cmd
	if sh.Name() == "pwsh" {
		c = exec.Command("powershell", "-NoProfile", "-NonInteractive", "-Command", cmdline)
	} else {
		c = exec.Command(sh.Interpreter(), "-c", cmdline)
	}
	c.Stdout = os.Stdout
	c.Stderr = os.Stderr
	c.Stdin = os.Stdin
	return c.Run()
}

func cmdShell(args []string) error {
	if len(args) < 1 {
		return fmt.Errorf("usage: grit shell <export|proxy> ...")
	}
	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}

	switch args[0] {
	case "export":
		if len(args) < 3 {
			return fmt.Errorf("usage: grit shell export <key> <value>")
		}
		fmt.Println(sh.Export(args[1], strings.Join(args[2:], " ")))
		return nil
	case "proxy":
		return printProxy(sh, args[1:])
	}
	return fmt.Errorf("unknown shell subcommand %q", args[0])
}

// printProxy 输出代理环境变量。无参数表示清除，单字母表示查 custom.toml 的端口别名。
func printProxy(sh shell.Shell, args []string) error {
	keys := []string{"https_proxy", "http_proxy", "all_proxy"}

	if len(args) == 0 {
		fmt.Fprintln(os.Stderr, "unset all proxies")
		for _, k := range keys {
			fmt.Println(sh.Export(k, ""))
		}
		return nil
	}

	port := args[0]
	if len(port) < 2 {
		cu, err := custom.Load(filepath.Join(gritRoot(false), "custom.toml"))
		if err != nil {
			return err
		}
		n, ok := cu.ProxyPorts[port]
		if !ok {
			return fmt.Errorf("no proxy port aliased to %q", port)
		}
		port = strconv.Itoa(n)
	}
	fmt.Fprintf(os.Stderr, "using proxies with port %s\n", port)

	fmt.Println(sh.Export("https_proxy", "http://127.0.0.1:"+port))
	fmt.Println(sh.Export("http_proxy", "http://127.0.0.1:"+port))
	fmt.Println(sh.Export("all_proxy", "socks5://127.0.0.1:"+port))
	return nil
}

func cmdList(args []string) error {
	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	if len(args) == 0 {
		return fmt.Errorf("usage: grit list <aliases|plugins|elements>")
	}

	switch args[0] {
	case "aliases":
		for _, a := range cfg.Aliases {
			fmt.Printf("%-8s %s\n", a.Name, a.Cmd)
		}
	case "plugins":
		for _, name := range cfg.Order {
			p := cfg.Plugins[name]
			fmt.Printf("%s (%s)\n", p.Name, p.Abbr)
			for _, k := range sortedKeys(p.Actions) {
				fmt.Printf("  %s%-4s exec   %s\n", p.Abbr, k, p.Actions[k])
			}
			for _, k := range sortedKeys(p.State) {
				// state 的 key 已经是完整命令名。
				fmt.Printf("  %-5s state  %s\n", k, p.State[k])
			}
		}
	case "elements":
		isWin := false
		if sh, e := targetShell("", nil); e == nil {
			isWin = sh.Name() == "pwsh"
		}
		for _, e := range cfg.Elements {
			p := e.Unix
			if isWin {
				p = e.Win
			}
			if p == "" {
				continue
			}
			fmt.Printf("%-4s %s\n", e.Key, ospath.Expand(p, isWin))
		}
	case "conv":
		for _, cv := range cfg.Converts {
			from := cv.InExt
			if from == "" {
				from = "*"
			}
			extra := ""
			if cv.Engine {
				extra = "  [engine]"
			}
			if cv.Stdout {
				extra += "  [stdout]"
			}
			fmt.Printf("%-10s %-6s -> %-5s %s%s\n", cv.Name, from, cv.Ext, cv.Tool, extra)
		}
	default:
		return fmt.Errorf("unknown list target %q", args[0])
	}
	return nil
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// matchesOS 判断声明里的平台限定是否适用于当前系统。
// 用 runtime.GOOS 而不是目标 shell：命令是否存在由宿主系统决定，
// 与路径风格由目标 shell 决定是两件事。
func matchesOS(want string) bool {
	return want == "" || want == runtime.GOOS
}

// gritRoot 返回用户配置目录。
// 设置 GRIT 时用仓库模式（配置与 defaults 都在仓库里）；
// 否则是独立分发模式，配置放在系统的用户配置目录下。
func gritRoot(isWin bool) string {
	if root := os.Getenv("GRIT"); root != "" {
		return ospath.Norm(root, isWin)
	}
	if dir, err := os.UserConfigDir(); err == nil {
		return ospath.Norm(filepath.Join(dir, "grit"), isWin)
	}
	if exe, err := os.Executable(); err == nil {
		return ospath.Norm(filepath.Dir(exe), isWin)
	}
	return ""
}

// cmdFile 实现 L2：四个文件动作，纯 IO，不依赖 shell。
func cmdFile(args []string) error {
	if len(args) < 1 {
		return fmt.Errorf("usage: grit file <backup|restore|catalyze|propagate> [-n] <key>...")
	}
	action := filemgr.Action(args[0])
	if !filemgr.Valid(action) {
		return fmt.Errorf("unknown action %q", args[0])
	}

	dry := false
	var keys []string
	for _, a := range args[1:] {
		switch a {
		case "-n", "--dry-run":
			dry = true
		default:
			keys = append(keys, a)
		}
	}

	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}
	isWin := sh.Name() == "pwsh"
	root := gritRoot(isWin)

	cu, err := custom.Load(filepath.Join(root, "custom.toml"))
	if err != nil {
		return err
	}

	set := filemgr.Set{
		Element:  map[string]string{},
		Oxide:    cu.Oxides,
		Oxygen:   map[string]string{},
		Backup:   ospath.Expand(cu.BackupRoot(isWin), isWin),
		IsWin:    isWin,
		Defaults: defaultsFS,
	}
	for _, e := range cfg.Elements {
		p := e.Unix
		if isWin {
			p = e.Win
		}
		if p == "" {
			continue
		}
		set.Element[e.Key] = ospath.Expand(p, isWin)
	}
	// 默认模板随二进制内嵌，因此不依赖仓库目录。
	for k, rel := range cfg.Oxygen {
		set.Oxygen[k] = filepath.ToSlash(rel)
	}

	if set.Backup == "" && action != filemgr.Catalyze {
		return fmt.Errorf("oxide_folder is not set in %s", cu.Path)
	}

	return filemgr.Run(set, action, keys, filemgr.Options{DryRun: dry, Out: os.Stdout})
}

// cmdMigrate 把 custom.json 转成 custom.toml，一次性、可预演。
func cmdMigrate(args []string) error {
	root := gritRoot(false)
	from := filepath.Join(root, "custom.json")
	to := filepath.Join(root, "custom.toml")
	force, dry := false, false

	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--from":
			if i+1 >= len(args) {
				return fmt.Errorf("--from needs a path")
			}
			from = args[i+1]
			i++
		case "--to":
			if i+1 >= len(args) {
				return fmt.Errorf("--to needs a path")
			}
			to = args[i+1]
			i++
		case "-f", "--force":
			force = true
		case "-n", "--dry-run":
			dry = true
		default:
			return fmt.Errorf("unknown flag %q", args[i])
		}
	}

	if _, err := os.Stat(from); err != nil {
		return fmt.Errorf("cannot read %s: %w", from, err)
	}
	if !dry {
		if _, err := os.Stat(to); err == nil && !force {
			return fmt.Errorf("%s already exists; pass --force to overwrite", to)
		}
	}

	cfg, err := migrate.FromFile(from)
	if err != nil {
		return err
	}
	out, err := migrate.Render(cfg)
	if err != nil {
		return err
	}

	if dry {
		_, err = os.Stdout.Write(out)
		return err
	}
	if err := os.WriteFile(to, out, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", to)
	fmt.Println("custom.json is no longer read; edit custom.toml from now on")
	return nil
}

// cmdSelfUpdate 接管 upox：更新本体与插件仓库。
func cmdSelfUpdate(args []string) error {
	force, noPlugins := false, false
	for _, a := range args {
		switch a {
		case "-f", "--force":
			force = true
		case "--no-plugins":
			noPlugins = true
		default:
			return fmt.Errorf("unknown flag %q", a)
		}
	}
	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}
	return selfupdate.Run(selfupdate.Options{
		Root:      gritRoot(false),
		Shell:     sh.Name(),
		Force:     force,
		NoPlugins: noPlugins,
		Out:       os.Stdout,
	})
}

// cmdConv 执行一条声明式格式转换。
func cmdConv(args []string) error {
	if len(args) < 2 {
		return fmt.Errorf("usage: grit conv <name> <file>")
	}
	name, file := args[0], args[1]

	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	inExt := strings.TrimPrefix(filepath.Ext(file), ".")
	cv, ok := cfg.ConvertFor(name, inExt)
	if !ok {
		return fmt.Errorf("unknown conversion %q (see `grit list conv`)", name)
	}
	if !matchesOS(cv.OS) {
		return fmt.Errorf("%s is not available on this platform", name)
	}
	return convert.Run(cv, file, os.Stdout)
}

// cmdComplete 输出某上下文下的候选值，由补全脚本在每次 TAB 时调用。
func cmdComplete(args []string) error {
	if len(args) < 1 {
		return fmt.Errorf("usage: grit complete <%s>", strings.Join(complete.Contexts(), "|"))
	}
	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	cu, err := custom.Load(filepath.Join(gritRoot(false), "custom.toml"))
	if err != nil {
		return err
	}
	vals, err := complete.Candidates(args[0], cfg, cu)
	if err != nil {
		return err
	}
	for _, v := range vals {
		fmt.Println(v)
	}
	return nil
}

// cmdCompletion 输出指定 shell 的补全脚本。
func cmdCompletion(args []string) error {
	sh, err := targetShell("", args)
	if err != nil {
		return err
	}
	s, err := complete.Script(sh.Name())
	if err != nil {
		return err
	}
	_, err = os.Stdout.WriteString(s)
	return err
}
