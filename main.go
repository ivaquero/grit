// runner 名取自 [run] 表的 runner 字段，是内部标识，不出现在命令树里。
const (
	runnerJulia  = "julia"
	runnerVSCode = "vscode"
)

// cmdRun 是 L2 的统一入口：所有「参数变换无法用静态模板表达」的动作都从这里进来。
//
// 命令树里因此不再有工具名 —— julia / vscode 只是插件名，
// 新增同类工具时改配置即可，不必再加一个子命令。
func cmdRun(args []string) error {
	if len(args) < 2 {
		return fmt.Errorf("usage: grit run <plugin> <action> [args...]")
	}
	pluginName, action, rest := args[0], args[1], args[2:]

	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	p, ok := cfg.Plugin(pluginName)
	if !ok {
		return fmt.Errorf("unknown plugin %q", pluginName)
	}

	if r, ok := p.Run[action]; ok {
		switch r.Runner {
		case runnerJulia:
			return runJulia(r.Op, rest)
		case runnerVSCode:
			return runVSCode(r.Op, rest)
		}
		return fmt.Errorf("%s/%s: unknown runner %q", pluginName, action, r.Runner)
	}

	// 纯转发模板也接受从这个入口调用：占位符替换规则与 state 通道一致，
	// 区别只在输出——这里直接执行，state 通道交给父 shell eval。
	tmpl, ok := p.Actions[action]
	if !ok {
		return fmt.Errorf("plugin %q has no action %q", pluginName, action)
	}
	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}
	return runShell(sh, renderTemplate(sh, tmpl, rest))
}

// renderTemplate 把 {shell} / {self} / {0} 替换成目标 shell 的等价写法。
func renderTemplate(sh shell.Shell, tmpl string, args []string) string {
	cmdline := strings.ReplaceAll(tmpl, "{shell}", sh.Interpreter())
	if self, e := os.Executable(); e == nil {
		cmdline = strings.ReplaceAll(cmdline, "{self}", sh.Quote(self))
	}
	if len(args) > 0 {
		quoted := make([]string, len(args))
		for i, a := range args {
			quoted[i] = sh.Quote(a)
		}
		return strings.ReplaceAll(cmdline, "{0}", strings.Join(quoted, " "))
	}
	// 无参数时把占位符连同前导空格一起去掉，让模板退化成无参调用。
	return strings.ReplaceAll(cmdline, " {0}", "")
}

// runJulia 管理 Julia 环境（L3）与包操作（L2）。
//
// 环境动作把 JULIA_PROJECT 写回父 shell；包操作把参数渲染成 Pkg 表达式
// 交给 julia 子进程。这一层之所以留在 Go 里，是因为
// 「包名列表变成 Julia 数组字面量」无法用静态模板表达。
func runJulia(op string, args []string) error {
	if !juliamgr.Valid(op) {
		return fmt.Errorf("unknown julia operation %q (want one of %s)",
			op, strings.Join(juliamgr.Ops, ", "))
	}

	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}
	isWin := sh.Name() == "pwsh"
	root := gritRoot(isWin)
	cu, err := custom.Load(filepath.Join(root, "custom.toml"))
	if err != nil {
		return err
	}

	// --env 可以出现在任意位置：jlis --env t A B
	envName := ""
	rest := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--env", "-e":
			if i+1 >= len(args) {
				return fmt.Errorf("--env needs an environment name")
			}
			envName = args[i+1]
			i++
		default:
			rest = append(rest, args[i])
		}
	}
	pkgs := rest

	switch op {
	case juliamgr.OpActivate:
		name := envName
		if len(pkgs) > 0 {
			name = pkgs[0]
		}
		spec, err := juliamgr.Resolve(name, cu, isWin)
		if err != nil {
			return err
		}
		// 只有这一行会被父 shell eval，提示信息不能混进 stdout。
		fmt.Println(sh.Export("JULIA_PROJECT", spec))
		return nil
	case juliamgr.OpDeactivate:
		fmt.Println(sh.Unset("JULIA_PROJECT"))
		return nil
	case juliamgr.OpCurrent:
		if v := os.Getenv("JULIA_PROJECT"); v != "" {
			fmt.Println(v)
			return nil
		}
		if spec, err := juliamgr.Resolve("", cu, isWin); err == nil {
			fmt.Printf("(unset; julia falls back to %s)\n", spec)
		} else {
			fmt.Println("(unset)")
		}
		return nil
	case juliamgr.OpEnvs:
		names := juliamgr.ShortcutNames(cu, isWin)
		if len(names) == 0 {
			fmt.Printf("no [env.julia] shortcuts in %s\n", cu.Path)
			return nil
		}
		for _, n := range names {
			spec, err := juliamgr.Resolve(n, cu, isWin)
			if err != nil {
				fmt.Printf("%-6s %v\n", n, err)
				continue
			}
			fmt.Printf("%-6s %s\n", n, spec)
		}
		return nil
	}

	if juliamgr.NeedsPackages(op) && len(pkgs) == 0 {
		return fmt.Errorf("%s needs at least one package", op)
	}
	if juliamgr.TakesNoPackages(op) && len(pkgs) > 0 {
		return fmt.Errorf("%s takes no package arguments", op)
	}

	// 优先级：--env > 当前 shell 已激活的 JULIA_PROJECT > 版本默认环境。
	spec := envName
	switch {
	case spec != "":
		if spec, err = juliamgr.Resolve(spec, cu, isWin); err != nil {
			return err
		}
	case os.Getenv("JULIA_PROJECT") != "":
		spec = os.Getenv("JULIA_PROJECT")
	default:
		if spec, err = juliamgr.Resolve("", cu, isWin); err != nil {
			return err
		}
	}

	switch op {
	case juliamgr.OpLeaves:
		names, err := juliamgr.Leaves(spec)
		if err != nil {
			return err
		}
		for _, n := range names {
			fmt.Println(n)
		}
		return nil
	case juliamgr.OpMaturity:
		m, err := juliamgr.CheckMaturity(spec)
		if err != nil {
			return err
		}
		fmt.Printf("total: %d\nimmature: %d\nmaturity: %d %%\n", m.Total, m.Immature, m.Rate())
		return nil
	}

	return juliamgr.RunPackage(op, pkgs, juliamgr.Options{
		Spec:  spec,
		Stdin: os.Stdin,
		Out:   os.Stdout,
		Err:   os.Stderr,
	})
}

// runVSCode 定位或清理 VS Code 的缓存。
// 默认只清无状态缓存；workspaceStorage 需要 -a 明确要求。
func runVSCode(op string, args []string) error {
	all, dry, dataDir := false, false, ""
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "-a", "--all":
			all = true
		case "-n", "--dry-run":
			dry = true
		case "--data-dir":
			if i+1 >= len(args) {
				return fmt.Errorf("--data-dir needs a path")
			}
			dataDir = args[i+1]
			i++
		default:
			return fmt.Errorf("unknown flag %q", args[i])
		}
	}

	dir, err := vscode.ResolveDataDir(dataDir)
	if err != nil {
		return err
	}

	switch op {
	case "dir":
		fmt.Println(dir)
		return nil
	case "clean":
	default:
		return fmt.Errorf("unknown vscode operation %q (want dir or clean)", op)
	}

	entries, err := vscode.Clean(vscode.Options{DataDir: dataDir, All: all, DryRun: dry})
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		fmt.Printf("nothing to clean in %s\n", dir)
		return nil
	}

	var total int64
	failed := 0
	for _, e := range entries {
		mark := "removed"
		if dry {
			mark = "[dry] would remove"
		}
		if e.Err != nil {
			mark = "error"
			failed++
		}
		fmt.Printf("%s %s (%s, %s)\n", mark, e.Path, e.Desc, humanBytes(e.Size))
		if e.Err != nil {
			fmt.Printf("  %v\n", e.Err)
		}
		total += e.Size
	}

	verb := "removed"
	if dry {
		verb = "would remove"
	}
	fmt.Printf("%s %d item(s), %s\n", verb, len(entries), humanBytes(total))
	if failed > 0 {
		return fmt.Errorf("%d of %d item(s) failed", failed, len(entries))
	}
	return nil
}

// cmdDoctor 输出启动期体检报告。
// 默认即使缺命令也返回 0：缺命令是可预期状态（brew 在 Windows 上就是没有），
// 需要门控时加 --strict。
func cmdDoctor(args []string) error {
	strict := false
	for _, a := range args {
		switch a {
		case "--strict":
			strict = true
		default:
			return fmt.Errorf("unknown flag %q", a)
		}
	}

	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	sh, err := targetShell("", nil)
	if err != nil {
		return err
	}
	isWin := sh.Name() == "pwsh"
	root := gritRoot(isWin)

	cu, err := custom.Load(filepath.Join(root, "custom.toml"))
	if err != nil {
		return err
	}

	rep := doctor.Check(cfg, cu, root, defaultsFS)
	printDoctor(rep, root)

	plugins := 0
	for _, e := range rep.Entries {
		if e.Scope == "plugin" {
			plugins++
		}
	}
	if len(rep.Missing) == 0 {
		fmt.Printf("\nall %d required command(s) available.\n", plugins)
		return nil
	}
	fmt.Printf("\n%d of %d plugin(s) miss a required command; `grit init --only-installed` skips them.\n",
		len(rep.Missing), plugins)
	if strict {
		return fmt.Errorf("%d required command(s) missing: %s",
			len(rep.Missing), strings.Join(rep.Missing, ", "))
	}
	return nil
}

func printDoctor(rep doctor.Report, root string) {
	fmt.Printf("grit doctor — %s\n", root)
	width := 0
	for _, e := range rep.Entries {
		if len(e.Name) > width {
			width = len(e.Name)
		}
	}
	scope := ""
	for _, e := range rep.Entries {
		if e.Scope != scope {
			scope = e.Scope
			fmt.Printf("\n%s\n", scope)
		}
		fmt.Printf("  %-5s %-*s  %s\n", e.Level, width, e.Name, e.Detail)
	}
}

func humanBytes(n int64) string {
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%d B", n)
	}
	div, exp := int64(unit), 0
	for m := n / unit; m >= unit; m /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %ciB", float64(n)/float64(div), "KMGTPE"[exp])
}
