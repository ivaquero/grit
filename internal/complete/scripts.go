package complete

import "fmt"

// Script 返回指定 shell 的补全脚本。
// 脚本本身不含任何配置数据，候选全部在运行时向 grit 查询。
func Script(name string) (string, error) {
	switch name {
	case "bash":
		return bashScript, nil
	case "zsh":
		return zshScript, nil
	case "pwsh", "powershell":
		return pwshScript, nil
	}
	return "", fmt.Errorf("no completion script for shell %q", name)
}

const bashScript = `# Grit completion — generated by ` + "`grit completion --shell bash`" + `
# Candidates are queried live, so this file never needs regenerating.

_grit_complete() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"

    if (( COMP_CWORD == 1 )); then
        COMPREPLY=( $(compgen -W "$(grit complete subcommands)" -- "$cur") )
        return
    fi

    case "${COMP_WORDS[1]}" in
        file)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(grit complete actions)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -W "$(grit complete keys)" -- "$cur") )
            fi
            ;;
        conv)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(grit complete converts)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -f -- "$cur") )
            fi
            ;;
        state)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(grit complete plugins)" -- "$cur") )
            elif (( COMP_CWORD == 3 )); then
                COMPREPLY=( $(compgen -W "$(grit complete state-actions "${COMP_WORDS[2]}")" -- "$cur") )
            else
                COMPREPLY=( $(compgen -f -- "$cur") )
            fi
            ;;
        julia)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(grit complete julia-ops)" -- "$cur") )
            elif [[ "${COMP_WORDS[2]}" == "activate" ]]; then
                COMPREPLY=( $(compgen -W "$(grit complete julia-envs)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -f -- "$cur") )
            fi
            ;;
        vscode)
            COMPREPLY=( $(compgen -W "$(grit complete vscode-actions)" -- "$cur") )
            ;;
        list)
            COMPREPLY=( $(compgen -W "$(grit complete list-targets)" -- "$cur") )
            ;;
        completion)
            COMPREPLY=( $(compgen -W "--shell $(grit complete shells)" -- "$cur") )
            ;;
        *)
            COMPREPLY=( $(compgen -f -- "$cur") )
            ;;
    esac
}
complete -F _grit_complete grit

_grit_complete_keys() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=( $(compgen -W "$(grit complete keys)" -- "$cur") )
}
complete -F _grit_complete_keys epf ipf iif ppgf

_grit_complete_ports() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=( $(compgen -W "$(grit complete ports)" -- "$cur") )
}
complete -F _grit_complete_ports pxy

_grit_complete_envs() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=( $(compgen -W "$(grit complete julia-envs)" -- "$cur") )
}
complete -F _grit_complete_envs jleat
`

const zshScript = `# Grit completion — generated by ` + "`grit completion --shell zsh`" + `
# Candidates are queried live, so this file never needs regenerating.

if ! typeset -f compdef >/dev/null 2>&1; then
    autoload -Uz compinit && compinit -i
fi

_grit_complete() {
    if (( CURRENT == 2 )); then
        compadd -- ${(f)"$(grit complete subcommands)"}
        return
    fi

    case $words[2] in
        file)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(grit complete actions)"}
            else
                compadd -- ${(f)"$(grit complete keys)"}
            fi
            ;;
        conv)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(grit complete converts)"}
            else
                _files
            fi
            ;;
        state)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(grit complete plugins)"}
            elif (( CURRENT == 4 )); then
                compadd -- ${(f)"$(grit complete state-actions $words[3])"}
            else
                _files
            fi
            ;;
        julia)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(grit complete julia-ops)"}
            elif [[ $words[3] == activate ]]; then
                compadd -- ${(f)"$(grit complete julia-envs)"}
            else
                _files
            fi
            ;;
        vscode)
            compadd -- ${(f)"$(grit complete vscode-actions)"}
            ;;
        list)
            compadd -- ${(f)"$(grit complete list-targets)"}
            ;;
        completion)
            compadd -- --shell ${(f)"$(grit complete shells)"}
            ;;
        *)
            _files
            ;;
    esac
}

compdef _grit_complete grit 2>/dev/null || true

_grit_complete_keys() {
    compadd -- ${(f)"$(grit complete keys)"}
}
compdef _grit_complete_keys epf ipf iif ppgf 2>/dev/null || true

_grit_complete_ports() {
    compadd -- ${(f)"$(grit complete ports)"}
}
compdef _grit_complete_ports pxy 2>/dev/null || true

_grit_complete_envs() {
    compadd -- ${(f)"$(grit complete julia-envs)"}
}
compdef _grit_complete_envs jleat 2>/dev/null || true
`

const pwshScript = `# Grit completion — generated by ` + "`grit completion --shell pwsh`" + `
# Candidates are queried live, so this file never needs regenerating.
# Native command completion requires PowerShell 6+; the function completers work on 5.1.

Register-ArgumentCompleter -CommandName grit -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $elements = $commandAst.CommandElements
    $cands = @()

    if ($elements.Count -le 2) {
        $cands = & grit complete subcommands
    }
    else {
        switch ($elements[1].Value) {
            'file' {
                if ($elements.Count -le 3) { $cands = & grit complete actions }
                else { $cands = & grit complete keys }
            }
            'conv' {
                if ($elements.Count -le 3) { $cands = & grit complete converts }
            }
            'state' {
                if ($elements.Count -le 3) { $cands = & grit complete plugins }
                elseif ($elements.Count -le 4) { $cands = & grit complete state-actions $elements[2].Value }
            }
            'julia' {
                if ($elements.Count -le 3) { $cands = & grit complete julia-ops }
                elseif ($elements.Count -le 4 -and $elements[2].Value -eq 'activate') {
                    $cands = & grit complete julia-envs
                }
            }
            'vscode' { $cands = & grit complete vscode-actions }
            'list' { $cands = & grit complete list-targets }
            'completion' { $cands = @('--shell') + (& grit complete shells) }
        }
    }

    $cands | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}

Register-ArgumentCompleter -CommandName epf, ipf, iif, ppgf -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    (& grit complete keys) | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}

Register-ArgumentCompleter -CommandName pxy -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    (& grit complete ports) | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}

Register-ArgumentCompleter -CommandName jleat -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    (& grit complete julia-envs) | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
`
