package complete

import "fmt"

// Script 返回指定 shell 的补全脚本。
// 脚本本身不含任何配置数据，候选全部在运行时向 goboot 查询。
func Script(name string) (string, error) {
	switch name {
	case "bash":
		return bashScript, nil
	case "zsh":
		return zshScript, nil
	case "pwsh", "powershell":
		return pwshScript, nil
	}
	return "", fmt.Errorf("no completion script for shell %q", name)
}

const bashScript = `# Goboot completion — generated by ` + "`goboot completion --shell bash`" + `
# Candidates are queried live, so this file never needs regenerating.

_goboot_complete() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"

    if (( COMP_CWORD == 1 )); then
        COMPREPLY=( $(compgen -W "$(goboot complete subcommands)" -- "$cur") )
        return
    fi

    case "${COMP_WORDS[1]}" in
        file)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(goboot complete actions)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -W "$(goboot complete keys)" -- "$cur") )
            fi
            ;;
        conv)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(goboot complete converts)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -f -- "$cur") )
            fi
            ;;
        state)
            if (( COMP_CWORD == 2 )); then
                COMPREPLY=( $(compgen -W "$(goboot complete plugins)" -- "$cur") )
            fi
            ;;
        list)
            COMPREPLY=( $(compgen -W "$(goboot complete list-targets)" -- "$cur") )
            ;;
        completion)
            COMPREPLY=( $(compgen -W "--shell $(goboot complete shells)" -- "$cur") )
            ;;
        *)
            COMPREPLY=( $(compgen -f -- "$cur") )
            ;;
    esac
}
complete -F _goboot_complete goboot

_goboot_complete_keys() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=( $(compgen -W "$(goboot complete keys)" -- "$cur") )
}
complete -F _goboot_complete_keys epf ipf iif ppgf

_goboot_complete_ports() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=( $(compgen -W "$(goboot complete ports)" -- "$cur") )
}
complete -F _goboot_complete_ports pxy
`

const zshScript = `# Goboot completion — generated by ` + "`goboot completion --shell zsh`" + `
# Candidates are queried live, so this file never needs regenerating.

if ! typeset -f compdef >/dev/null 2>&1; then
    autoload -Uz compinit && compinit -i
fi

_goboot_complete() {
    if (( CURRENT == 2 )); then
        compadd -- ${(f)"$(goboot complete subcommands)"}
        return
    fi

    case $words[2] in
        file)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(goboot complete actions)"}
            else
                compadd -- ${(f)"$(goboot complete keys)"}
            fi
            ;;
        conv)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(goboot complete converts)"}
            else
                _files
            fi
            ;;
        state)
            if (( CURRENT == 3 )); then
                compadd -- ${(f)"$(goboot complete plugins)"}
            fi
            ;;
        list)
            compadd -- ${(f)"$(goboot complete list-targets)"}
            ;;
        completion)
            compadd -- --shell ${(f)"$(goboot complete shells)"}
            ;;
        *)
            _files
            ;;
    esac
}

compdef _goboot_complete goboot 2>/dev/null || true

_goboot_complete_keys() {
    compadd -- ${(f)"$(goboot complete keys)"}
}
compdef _goboot_complete_keys epf ipf iif ppgf 2>/dev/null || true

_goboot_complete_ports() {
    compadd -- ${(f)"$(goboot complete ports)"}
}
compdef _goboot_complete_ports pxy 2>/dev/null || true
`

const pwshScript = `# Goboot completion — generated by ` + "`goboot completion --shell pwsh`" + `
# Candidates are queried live, so this file never needs regenerating.
# Native command completion requires PowerShell 6+; the function completers work on 5.1.

Register-ArgumentCompleter -CommandName goboot -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $elements = $commandAst.CommandElements
    $cands = @()

    if ($elements.Count -le 2) {
        $cands = & goboot complete subcommands
    }
    else {
        switch ($elements[1].Value) {
            'file' {
                if ($elements.Count -le 3) { $cands = & goboot complete actions }
                else { $cands = & goboot complete keys }
            }
            'conv' {
                if ($elements.Count -le 3) { $cands = & goboot complete converts }
            }
            'state' {
                if ($elements.Count -le 3) { $cands = & goboot complete plugins }
            }
            'list' { $cands = & goboot complete list-targets }
            'completion' { $cands = @('--shell') + (& goboot complete shells) }
        }
    }

    $cands | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}

Register-ArgumentCompleter -CommandName epf, ipf, iif, ppgf -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    (& goboot complete keys) | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}

Register-ArgumentCompleter -CommandName pxy -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    (& goboot complete ports) | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
`
